//! Words an engine refuses as an unquoted table or column name.
//!
//! Data, not logic: [`needs_quoting`] is the one function that reads it, and
//! [`insertion_form`](crate::insertion::insertion_form) the one caller. Every
//! list is **lowercase and sorted** — a test holds both, because the lookup is a
//! binary search and a misplaced entry would silently stop matching.
//!
//! Each list errs on the side of quoting: a word that is not known to be safe
//! costs a pair of quotes, a reserved word left bare costs a rejected
//! statement ([ADR-0057](../../../docs/adr/0057-editor-completion-reads-the-catalog-cache.md)).
//!
//! # Sources, checked on 2026-10-21
//!
//! | List | Source | Rule |
//! |---|---|---|
//! | `POSTGRES` | `src/include/parser/kwlist.h` at tag `REL_18_6` | the `RESERVED_KEYWORD` and `TYPE_FUNC_NAME_KEYWORD` entries: the words PostgreSQL refuses as a table name |
//! | `SQLITE` | [SQLite keywords](https://www.sqlite.org/lang_keywords.html) | all 147: SQLite lets some of them through as identifiers, but not by a documented rule |
//! | `MYSQL` | `sql/lex.h` and `sql/sql_yacc.yy` at tag `mysql-8.4.0` | the `SYM` and `SYM_HK` words whose token appears in none of the `ident_keyword*` and `label_keyword` rules |
//! | `MARIADB` | `sql/lex.h` and `sql/sql_yacc.yy` at branch `11.8`, commit `c20c21d7a1cd` | the `symbols[]` words whose token is outside the closure of `keyword_ident` |
//! | `DUCKDB` | `third_party/libpg_query/include/parser/kwlist.hpp` of DuckDB `v1.5.6`, as bundled by `libduckdb-sys` 1.10506.1 (checked on 2026-10-23) | the `RESERVED_KEYWORD` and `TYPE_FUNC_NAME_KEYWORD` entries, PostgreSQL's rule on DuckDB's grammar |
//!
//! The MySQL and MariaDB pages that list reserved words answer a scripted
//! request with a 403, so both lists come from the grammar that decides what is
//! reserved, which also makes them a superset of the documentation's: the
//! grammar reserves what the parser cannot take as an identifier, the
//! documentation says what a user may not. The extraction and its limits are
//! recorded in `docs/RESEARCH-NOTES.md`.
//!
//! One driver serves MySQL and MariaDB (ADR-0050), and the dialect does not say
//! which server answered: the two lists are read together. **They are pinned to
//! the versions above**: a word a later MySQL or MariaDB reserves is inserted
//! bare until the lists are re-extracted (`/versions`), which is the cost of
//! reading a grammar rather than asking the server.

