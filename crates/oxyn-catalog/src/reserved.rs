/// Does a lowercase name need quotes in this dialect?
///
/// `None` for a dialect whose reserved words are not recorded here: the caller
/// quotes, because a name that is not known to be safe is quoted. That includes
/// Redshift, whose grammar differs from PostgreSQL's (ADR-0003), and standard
/// SQL, which has no engine behind it.
#[must_use]
pub(crate) fn needs_quoting(dialect: SqlDialect, lowercase: &str) -> Option<bool> {
    let found = |list: &[&str]| list.binary_search(&lowercase).is_ok();
    match dialect {
        SqlDialect::Postgres => Some(found(POSTGRES)),
        SqlDialect::Sqlite => Some(found(SQLITE)),
        SqlDialect::MySql => Some(found(MYSQL) || found(MARIADB)),
        SqlDialect::DuckDb => Some(found(DUCKDB)),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const LISTS: [(&str, &[&str]); 5] = [
        ("POSTGRES", POSTGRES),
        ("SQLITE", SQLITE),
        ("MYSQL", MYSQL),
        ("MARIADB", MARIADB),
        ("DUCKDB", DUCKDB),
    ];

    #[test]
    fn every_list_is_lowercase_sorted_and_without_duplicates() {
        // The lookup is a binary search: one misplaced word stops matching,
        // and nothing else would notice.
        for (name, list) in LISTS {
            assert!(
                list.windows(2).all(|pair| pair[0] < pair[1]),
                "{name} must be strictly ascending"
            );
            assert!(
                list.iter().all(|word| {
                    word.bytes()
                        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
                }),
                "{name} holds lowercase words only"
            );
        }
    }

    #[test]
    fn the_lists_keep_the_sizes_they_were_extracted_with() {
        // A hand edit that drops a row would otherwise pass: the size is the
        // cheapest witness that the list is the extraction.
        assert_eq!(POSTGRES.len(), 101);
        assert_eq!(SQLITE.len(), 147);
        assert_eq!(MYSQL.len(), 264);
        assert_eq!(MARIADB.len(), 247);
        assert_eq!(DUCKDB.len(), 110);
    }

    #[test]
    fn duckdb_reserves_its_own_words_beyond_postgres() {
        // `at` stopped a test table's column at parse time; `qualify`, `pivot`
        // and `summarize` are DuckDB's own clauses.
        for word in ["at", "qualify", "pivot", "summarize", "select"] {
            assert_eq!(
                needs_quoting(SqlDialect::DuckDb, word),
                Some(true),
                "{word}"
            );
        }
        for word in ["users", "name", "status", "type"] {
            assert_eq!(
                needs_quoting(SqlDialect::DuckDb, word),
                Some(false),
                "{word}"
            );
        }
    }

    #[test]
    fn the_words_the_documentation_names_are_reserved() {
        // PostgreSQL 18, Appendix C: ORDER and GROUP "reserved, requires AS",
        // USER and TABLE "reserved".
        for word in ["order", "group", "user", "table"] {
            assert_eq!(needs_quoting(SqlDialect::Postgres, word), Some(true));
        }
        assert_eq!(needs_quoting(SqlDialect::Postgres, "users"), Some(false));
    }

    #[test]
    fn mysql_reads_both_lists_because_one_driver_serves_both_servers() {
        // `offset` and `returning` are reserved by MariaDB only; `rank` by MySQL only.
        for word in ["offset", "returning", "rank", "select"] {
            assert_eq!(needs_quoting(SqlDialect::MySql, word), Some(true), "{word}");
        }
        // Words a MySQL table is commonly called.
        for word in ["status", "name", "type", "comment", "date", "count"] {
            assert_eq!(
                needs_quoting(SqlDialect::MySql, word),
                Some(false),
                "{word}"
            );
        }
    }

    #[test]
    fn a_dialect_without_a_list_answers_unknown() {
        for dialect in [
            SqlDialect::Ansi,
            SqlDialect::Redshift,
            SqlDialect::SqlServer,
        ] {
            assert_eq!(needs_quoting(dialect, "users"), None);
        }
    }
}
